# save_baseline.sh
# ----------------
# Phase 0 N0-T4 helper. Captures the current libnotification.so /
# libnotification-ex.so sizes into scripts/size_baseline.txt so operators
# can lock in a new ceiling after an intentional cleanup.
#
# Usage:
#   scripts/save_baseline.sh [BUILD_DIR]
#
# BUILD_DIR defaults to ./build. Writes both `size` tool output and a
# simple "<bytes> <lib>" line per library.

set -euo pipefail

BUILD_DIR="${1:-${CMAKE_BINARY_DIR:-build}}"
OUT_DIR="$(cd "$(dirname "$0")" && pwd)"
OUT_FILE="${OUT_DIR}/size_baseline.txt"

LIBS=(libnotification.so libnotification-ex.so)

{
  echo "# Auto-generated by scripts/save_baseline.sh"
  echo "# Date: $(date -u +%FT%TZ)"
  echo "# Build dir: ${BUILD_DIR}"
  echo
  for lib in "${LIBS[@]}"; do
    path=$(find "${BUILD_DIR}" -name "${lib}" -type f -print -quit 2>/dev/null || true)
    if [[ -z "${path}" ]]; then
      echo "# ${lib}: not found"
      continue
    fi
    bytes=$(stat -c%s "${path}")
    echo "${bytes} ${lib}"
    if command -v size >/dev/null 2>&1; then
      echo "# size(1):"
      size "${path}" | sed 's/^/# /'
    fi
    echo
  done
} > "${OUT_FILE}"

echo "[size] baseline written: ${OUT_FILE}"
cat "${OUT_FILE}"
